# 🎸 ドレミ → しゅうはすう けいさんき
# おとの たかさ（しゅうはすう Hz）を けいさんするよ。
#
# やりかた:
#   1. 下の # TODO の しき を かく
#   2. じっこうすると、ドレミの しゅうはすうが ひょうで でる

# きじゅんの おと: ラ(A4) = 440 Hz
BASE_FREQ = 440

# おとの なまえ → きじゅん(ラ)から なんはんおん はなれているか の じしょ
semitones = {
    "ド":   -9,
    "レ":   -7,
    "ミ":   -5,
    "ファ": -4,
    "ソ":   -2,
    "ラ":    0,
    "シ":    2,
    "ド↑":   3,
}


def to_freq(name):
    n = semitones[name]   # ラから なんはんおん はなれているか

    # TODO: 平均律の しき を かこう！
    # ヒント: 1オクターブ(12はんおん)で しゅうはすうは 2ばい。
    #   だから 1はんおんは「2 の 12ぶんの1 じょう」。
    #   しき →  BASE_FREQ * (2 ** (n / 12))
    freq = BASE_FREQ   # ← ここを なおそう！

    return round(freq, 1)   # みやすく、小数第1いちまで


print("🎵 ドレミの しゅうはすう（Hz）")
print("-" * 24)
for name in semitones:
    print(f"  {name:<3}  {to_freq(name):>7} Hz")
